let currentLanguage = localStorage.getItem("siteLanguage") || "ro";
const originalText = new WeakMap();
const languageButton = document.createElement("button");

languageButton.className = "language-toggle";
languageButton.type = "button";
document.querySelector(".site-header")?.appendChild(languageButton);

function translateTextNode(node, language) {
  if (!originalText.has(node)) {
    originalText.set(node, node.nodeValue);
  }

  const original = originalText.get(node);
  const trimmed = original.trim();

  if (!trimmed) {
    return;
  }

  const leading = original.match(/^\s*/)[0];
  const trailing = original.match(/\s*$/)[0];
  const translated = language === "en" ? translations[trimmed] || trimmed : trimmed;
  node.nodeValue = `${leading}${translated}${trailing}`;
}

function applyLanguage(language) {
  document.documentElement.lang = language;
  languageButton.textContent = language === "ro" ? "EN" : "RO";
  languageButton.setAttribute("aria-label", language === "ro" ? "Translate to English" : "Comuta in romana");

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || ["SCRIPT", "STYLE"].includes(parent.tagName)) {
        return NodeFilter.FILTER_REJECT;
      }
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  while (walker.nextNode()) {
    translateTextNode(walker.currentNode, language);
  }
}

languageButton.addEventListener("click", () => {
  currentLanguage = currentLanguage === "ro" ? "en" : "ro";
  localStorage.setItem("siteLanguage", currentLanguage);
  applyLanguage(currentLanguage);
});

applyLanguage(currentLanguage);
